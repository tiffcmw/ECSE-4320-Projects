#!/usr/bin/env python3
"""Generates build/fma_gen.h: functions with N independent fmla accumulators (N = 1..30), .4s and .2d."""
import sys
MAXACC, REPEAT = 30, 8
out = ["/* generated by scripts/gen_fma.py */", "typedef void (*fmafn)(long);", "#define FMA_MAXACC %d" % MAXACC, "#define FMA_REPEAT %d" % REPEAT]
clob = ", ".join('"v%d"' % i for i in range(32))
for arr in ("4s", "2d"):
    for n in range(1, MAXACC + 1):
        body = "".join("fmla v%d.%s, v30.%s, v31.%s\\n" % (i, arr, arr, arr) for i in range(n))
        init = "".join("movi v%d.16b, #0\\n" % i for i in range(n)) + "fmov v30.%s, #1.0\\nfmov v31.%s, #1.0\\n" % (arr, arr)
        out.append('static void fma_%s_%d(long iters) { __asm__ volatile("%smov x9, %%0\\n1:\\n.rept %d\\n%s.endr\\nsubs x9, x9, #1\\nb.ne 1b\\n" :: "r"(iters) : "x9", "cc", %s); }' % (arr, n, init, REPEAT, body, clob))
    out.append("static const fmafn FMA_%s[] = {%s};" % (arr.upper(), ", ".join("fma_%s_%d" % (arr, n) for n in range(1, MAXACC + 1))))
open(sys.argv[1], "w").write("\n".join(out) + "\n")
