#!/usr/bin/env python3
"""Phase 2: vectorization evidence. For every kernel x dtype x build:
  - compiler remarks (loop-vectorize passed/missed/analysis, slp-vectorizer) -> vecreports/remarks/
  - disassembly of the kernel (objdump) -> instruction statistics, and the largest loop body (<= 24 lines) -> vecreports/asm/
  - vecreports/summary.md (generated table)
Run from anywhere: python3 scripts/vecreport.py (requires build/obj from scripts/build.sh)."""
import os, re, subprocess, sys, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
def sh(c): return subprocess.run(["bash", "-c", c], capture_output=True, text=True)
cfg = lambda v: sh("source scripts/config.sh; echo $%s" % v).stdout.split()
KERNELS, DTYPES, BUILDS = cfg("KERNELS"), cfg("DTYPES"), cfg("BUILDS")
flags = {b: sh("source scripts/config.sh; build_flags %s" % b).stdout.strip() for b in BUILDS}
os.makedirs("vecreports/remarks", exist_ok=True); os.makedirs("vecreports/asm", exist_ok=True)
REM = "-Rpass='loop-vectorize|slp-vectorizer' -Rpass-missed=loop-vectorize -Rpass-analysis=loop-vectorize"
BRANCH = re.compile(r"^\s*([0-9a-f]+):\s+[0-9a-f]{8}\s+(\S+)\s*(.*)$")

def disasm(b, k, d):
    sym = "_kern_%s_%s_%s" % (k, d, b)
    out = sh("objdump -d --disassemble-symbols=%s build/obj/%s/%s_%s.o" % (sym, b, k, d)).stdout
    ins = []
    for line in out.splitlines():
        m = BRANCH.match(line)
        if m: ins.append((int(m.group(1), 16), m.group(2), m.group(3), line.strip()))
    return ins

def loops(ins):
    addr_idx = {a: i for i, (a, *_ ) in enumerate(ins)}
    res = []
    for i, (a, mn, ops, _) in enumerate(ins):
        if mn.startswith("b") or mn in ("cbz", "cbnz", "tbz", "tbnz"):
            m = re.search(r"0x([0-9a-f]+)", ops)
            if m and int(m.group(1), 16) < a and int(m.group(1), 16) in addr_idx:
                res.append((addr_idx[int(m.group(1), 16)], i))
    return res

def stats(ins, lp):
    body = ins[lp[0]:lp[1] + 1] if lp else []
    c = collections.Counter()
    for _, mn, ops, _ in body:
        base = mn.split(".")[0]
        arr = mn.split(".")[1] if "." in mn else ""
        vec = bool(re.search(r"\b[vq]\d", ops)) and arr in ("4s", "2d", "2s", "4h", "8h", "16b", "8b", "")
        if base in ("fmla", "fmls") : c["fmla_vec"] += 1
        elif base == "fmadd" or base == "fmsub": c["fmadd_scalar"] += 1
        elif base in ("fmul", "fadd", "fsub"):
            c["%s_%s" % (base, "vec" if arr else "scalar")] += 1
        elif base in ("ldp", "ldr", "ld1", "ld2", "ld4", "ldur") : c["load_q" if re.search(r"\bq\d", ops) else "load_other"] += 1
        elif base in ("stp", "str", "st1", "st2", "st4", "stur"): c["store_q" if re.search(r"\bq\d", ops) else "store_other"] += 1
        elif base in ("mul", "add") and arr: c["%s_vec" % base] += 1
    return c, len(body)

def remark_summary(txt):
    vf = re.findall(r"vectorized loop \(vectorization width: (\d+), interleaved count: (\d+)\)", txt)
    missed = re.findall(r"remark: (.*?) \[-Rpass-(?:missed|analysis)=loop-vectorize\]", txt)
    slp = "vectorized with cost" in txt
    return vf, missed, slp

rows = []
for k in KERNELS:
    for d in DTYPES:
        for b in BUILDS:
            src = "src/kernel_tpl.c"
            r = sh("clang -std=c11 %s %s -DKERN=%s -DDT=%s -DBUILD=%s -c %s -o /dev/null" % (flags[b], REM, k, d, b, src))
            txt = r.stderr
            open("vecreports/remarks/%s_%s_%s.txt" % (b, k, d), "w").write(txt)
            vf, missed, slp = remark_summary(txt)
            ins = disasm(b, k, d)
            lps = loops(ins)
            best = max(lps, key=lambda t: t[1] - t[0]) if lps else None
            # largest loop containing a vector op if any, else largest loop
            vec_lps = [l for l in lps if any(re.search(r"\.(4s|2d|2s)\b", ins[j][1]) or re.search(r"\.(4s|2d)", ins[j][2]) for j in range(l[0], l[1] + 1))]
            if vec_lps: best = max(vec_lps, key=lambda t: t[1] - t[0])
            c, n = stats(ins, best)
            body = ins[best[0]:best[1] + 1] if best else []
            with open("vecreports/asm/%s_%s_%s.s" % (b, k, d), "w") as f:
                f.write("; %s %s %s: largest loop body (%d instr)%s\n" % (b, k, d, n, " [truncated to 24]" if n > 24 else ""))
                for _, _, _, line in body[:24]: f.write(re.sub(r"^[0-9a-f]+:\s+[0-9a-f]{8}\s+", "", line) + "\n")
            n_vec_loops = len(vec_lps)
            has_scalar_tail = any(re.search(r"\b[sd]\d", i[2]) and i[1].split(".")[0] in ("ldr", "fmadd", "fmul", "fadd") and not re.search(r"\.", i[1]) for i in ins) and bool(vf)
            rows.append((k, d, b, vf, missed, slp, c, n, n_vec_loops, has_scalar_tail, len(ins)))

with open("vecreports/summary.md", "w") as f:
    f.write("# Vectorization summary (generated by scripts/vecreport.py)\n\n")
    f.write("VF = vectorization width (lanes), IC = interleave count. Elements per main-loop iteration = VF x IC. Loop columns count instructions in the largest vector loop body of the object (the main loop). ")
    f.write("`fmla.v` = vector fused multiply-add (fmla .4s/.2d), `fmadd.s` = scalar fused multiply-add, `ldp/ldr q` and `stp/str q` = 128-bit vector memory ops. 'remark' is the loop-vectorize passed/missed text.\n\n")
    f.write("| kernel | dtype | build | vectorized | VF x IC | main-loop instr | fmla.v | fmul.v | fadd.v | fmadd.s | ld q | st q | remark (first missed/analysis) |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
    for k, d, b, vf, missed, slp, c, n, nvl, st, tot in rows:
        v = "yes" if vf else "no"
        vfs = ", ".join("%sx%s" % x for x in vf) if vf else "-"
        m = (missed[0] if missed else "").replace("|", "/")[:90]
        f.write("| %s | %s | %s | %s | %s | %d | %d | %d | %d | %d | %d | %d | %s |\n" % (k, d, b, v, vfs, n, c["fmla_vec"], c["fmul_vec"], c["fadd_vec"], c["fmadd_scalar"], c["load_q"], c["store_q"], m))
print("wrote vecreports/summary.md and %d remark/asm files" % len(rows))
