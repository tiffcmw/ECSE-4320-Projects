#!/usr/bin/env bash
# Builds all kernel objects (one TU per kernel x dtype x build), the registry, bench and test binaries.
set -euo pipefail
cd "$(dirname "$0")/.."
source scripts/config.sh
mkdir -p build/obj bin
REG=build/registry_gen.h
{
  echo "/* generated by scripts/build.sh */"
  for b in $BUILDS; do for k in $KERNELS; do for d in $DTYPES; do
    echo "double kern_${k}_${d}_${b}(size_t, double, const void*, void*, void*);"
  done; done; done
  echo "static const struct kentry REGISTRY[] = {"
  for b in $BUILDS; do for k in $KERNELS; do for d in $DTYPES; do
    echo "  {\"$k\",\"$d\",\"$b\",kern_${k}_${d}_${b}},"
  done; done; done
  echo "};"
} > $REG
jobs_file=$(mktemp)
for b in $BUILDS; do
  mkdir -p build/obj/$b
  fl=$(build_flags $b)
  for k in $KERNELS; do for d in $DTYPES; do
    echo "$CC $COMMON_FLAGS $fl -DKERN=$k -DDT=$d -DBUILD=$b -c src/kernel_tpl.c -o build/obj/$b/${k}_${d}.o" >> $jobs_file
  done; done
done
xargs -P 8 -I{} sh -c "{}" < $jobs_file
rm -f $jobs_file
OBJS=$(ls build/obj/*/*.o)
HF="-std=c11 -O2 -Wall -Wextra -Wno-unused-parameter -Isrc -Ibuild"
$CC $HF src/bench.c $OBJS -o bin/bench
$CC $HF -ffp-contract=off tests/test_kernels.c $OBJS -o bin/test_kernels
echo "build ok: $(ls build/obj/*/*.o | wc -l) kernel objects"
